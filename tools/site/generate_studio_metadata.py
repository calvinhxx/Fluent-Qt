"""Build the Studio input and Designer contracts from the shipped registrations."""
import argparse
import json
from pathlib import Path
from urllib.parse import quote

from generate_playgrounds import descriptors
from studio_i18n import validate_studio_locales

ROOT = Path(__file__).resolve().parents[2]


def generate():
    widgets = json.loads((ROOT / "tools/designer/widgets.json").read_text())
    names = {w.get("surface", w["name"].removeprefix("Fluent")): w["name"] for w in widgets}
    fields = {}
    for route, spec in descriptors().items():
        name = spec.get("title") or "".join(word.capitalize() for word in route.split("-"))
        fields[name] = {field["id"]: {key: field[key] for key in
                        ("type", "options", "nullable", "maximumLength", "maximumRows", "maximumItems")
                        if key in field} for field in spec["properties"]}
        for field in spec["properties"]:
            if field["type"] in ("date", "time", "datetime") and field.get("property", field["id"]) != field["id"]:
                fields[name][field["id"]]["property"] = field["property"]
    scenes = {path.stem: "data:text/plain;charset=utf-8," + quote(path.read_text(), safe="")
              for path in (ROOT / "app/view/widgets/samples/qmlbridge").glob("*.qml")}

    def export(name, data):
        rows = [f"  {json.dumps(k)}: {json.dumps(v, separators=(',', ':'))}" for k, v in sorted(data.items())]
        return f"export const {name} = {{\n" + ",\n".join(rows) + "\n};\n"
    return ("// Generated by tools/site/generate_studio_metadata.py.\n"
            + export("designerClasses", names) + export("playgroundFields", fields) + export("qmlScenes", scenes))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "site/studio/studio-metadata.mjs"
    content = generate()
    validate_studio_locales()
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("Refresh Studio metadata with tools/site/generate_studio_metadata.py")
    else:
        path.write_text(content)

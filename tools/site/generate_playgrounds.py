#!/usr/bin/env python3
"""Generate Gallery factories and website descriptors from reviewed component recipes."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import shutil

ROOT = Path(__file__).resolve().parents[2]


def outputs(root: Path) -> dict[Path, str]:
    assets = root / "app/assets/playgrounds"
    specs = json.loads((assets / "components.json").read_text(encoding="utf-8"))
    result = {}
    includes = {'#include "GalleryPlaygroundFactory.h"'}
    factories = []
    routes = ["button"]
    for spec in specs:
        route = spec["component"]
        assert route not in routes, route
        routes.append(route)
        cpp = spec["recipe"]["cpp"]
        includes.update(cpp["imports"].splitlines())
        includes.update(spec.get("factoryIncludes", []))
        surface = spec.get("surface", "control")
        parent_expr = "stage" if surface == "host" else "parent"
        pre_setup = ""
        if surface == "host":
            w, h = spec.get("hostSize") or spec.get("previewSize") or [360, 220]
            pre_setup = (
                f"        auto* host = new QWidget(parent, Qt::Window | Qt::FramelessWindowHint);\n"
                f"        host->setAttribute(Qt::WA_DontShowOnScreen, true);\n"
                f"        host->setFixedSize({w}, {h});\n"
                f"        auto* stage = new QWidget(host);\n"
                f"        stage->setFixedSize({w}, {h});\n"
            )
        setup = cpp["setup"].replace("%PARENT%", parent_expr)
        post_setup = spec.get("factorySetup", "").replace("%PARENT%", parent_expr)
        if post_setup and not post_setup.endswith("\n"):
            post_setup += "\n"
        factories.append(
            f'    if (route == QStringLiteral("{route}")) {{\n{pre_setup}{setup}{post_setup}'
            f'        return {{{surface}, control}};\n    }}'
        )
        descriptor = {"version": 1, **{k: v for k, v in spec.items() if k not in ("factorySetup", "factoryIncludes", "hostSize")}}
        descriptor.setdefault("presets", [{"id": "default", "label": {"en": "Initial example", "zh": "初始示例"}, "values": {}}])
        result[assets / f"{route}.json"] = json.dumps(descriptor, ensure_ascii=False, indent=2) + "\n"
    joined_routes = "\n".join(f'        QStringLiteral("{route}"),' for route in routes)
    source = "// Generated by tools/site/generate_playgrounds.py; edit components.json.\n"
    source += "\n".join(sorted(includes)) + "\n"
    source += "\nnamespace fluent::gallery {\n"
    source += f"QStringList playgroundRoutes()\n{{\n    return {{\n{joined_routes}\n    }};\n}}\n\n"
    source += "PlaygroundControl createPlaygroundControl(const QString& route, QWidget* parent)\n{\n"
    source += "\n".join(factories) + "\n    return {};\n}\n} // namespace fluent::gallery\n"
    formatter = root / ".venv-format/bin/clang-format"
    if not formatter.is_file():
        formatter = root / ".venv-format/Scripts/clang-format.exe"
    if not formatter.is_file():
        formatter = Path(shutil.which("clang-format") or "clang-format")
    version = subprocess.run([str(formatter), "--version"], text=True, capture_output=True, check=True).stdout
    if "version 22.1.8" not in version:
        raise RuntimeError("Playground generation requires clang-format 22.1.8")
    source = subprocess.run([str(formatter)], input=source, text=True, capture_output=True, check=True).stdout
    result[root / "app/view/widgets/GalleryPlaygroundFactory.cpp"] = source
    qrc = root / "app/playground_resources.qrc"
    result[qrc] = '<RCC>\n  <qresource prefix="/app/playgrounds">\n' + "".join(
        f'    <file alias="{route}.json">assets/playgrounds/{route}.json</file>\n' for route in routes[1:]
    ) + "  </qresource>\n</RCC>\n"
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs(ROOT).items():
        data = content.encode("utf-8")
        if path.exists() and path.read_bytes() == data:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_bytes(data)
    if stale:
        raise SystemExit("Stale playground assets: " + ", ".join(stale))


if __name__ == "__main__":
    main()

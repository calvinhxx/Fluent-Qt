#!/usr/bin/env python3
"""Generate Gallery factories and website descriptors from reviewed component recipes."""
from __future__ import annotations

import argparse
from functools import lru_cache
import re
import json
from pathlib import Path
import subprocess
import shutil

ROOT = Path(__file__).resolve().parents[2]


@lru_cache(maxsize=1)
def descriptors(root: Path = ROOT) -> dict:
    """Return exactly the public descriptors consumed by the Gallery and the website."""
    assets = root / "app/assets/playgrounds"
    result = {"button": json.loads((assets / "button.json").read_text(encoding="utf-8"))}
    for spec in json.loads((assets / "components.json").read_text(encoding="utf-8")):
        route = spec["component"]
        if not re.fullmatch(r"[a-z][a-z0-9-]*", route) or route in result:
            raise ValueError(f"Invalid or duplicate playground route: {route}")
        descriptor = {"version": 1, **{k: v for k, v in spec.items()
                      if k not in ("factorySetup", "factoryIncludes", "hostSize", "compileGuard")}}
        descriptor.setdefault("presets", [{"id": "default", "label": {"en": "Initial example", "zh": "初始示例"}, "values": {}}])
        result[route] = descriptor
    return result


def write_resources(directory: Path) -> None:
    """Qt reads the QRC at configure time. Keep its paths relative to the build tree."""
    directory.mkdir(parents=True, exist_ok=True)
    entries = []
    for route, data in descriptors().items():
        if route == "button":  # Its handwritten resource is already in gallery_resources.qrc.
            continue
        filename = route + ".json"
        content = (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
        target = directory / filename
        if not target.is_file() or target.read_bytes() != content:
            target.write_bytes(content)
        entries.append(f"    <file>{filename}</file>\n")
    qrc = directory / "playground_resources.qrc"
    content = ('<RCC>\n  <qresource prefix="/app/playgrounds">\n' + "".join(entries) + "  </qresource>\n</RCC>\n").encode()
    if not qrc.is_file() or qrc.read_bytes() != content:
        qrc.write_bytes(content)


def outputs(root: Path) -> dict[Path, str]:
    assets = root / "app/assets/playgrounds"
    specs = json.loads((assets / "components.json").read_text(encoding="utf-8"))
    result = {}
    includes = {'#include "GalleryPlaygroundFactory.h"'}
    guarded_includes: dict[str, set[str]] = {}
    factories = []
    routes: dict[str, str | None] = {"button": None}
    for spec in specs:
        route = spec["component"]
        if route in routes:
            raise ValueError(f"Duplicate playground route: {route}")
        guard = spec.get("compileGuard")
        routes[route] = guard
        cpp = spec["recipe"]["cpp"]
        spec_includes = set(cpp["imports"].splitlines()) | set(spec.get("factoryIncludes", []))
        if guard:
            guarded_includes.setdefault(guard, set()).update(spec_includes)
        else:
            includes.update(spec_includes)
        surface = spec.get("surface", "control")
        parent_expr = "stage" if surface == "host" else "parent"
        pre_setup = ""
        if surface == "host":
            w, h = spec.get("hostSize") or spec.get("previewSize") or [360, 220]
            pre_setup = (
                f"        auto* host = new QWidget(parent, Qt::Window | Qt::FramelessWindowHint);\n"
                f"        host->setAttribute(Qt::WA_DontShowOnScreen, true);\n"
                f"        host->setFixedSize({w}, {h});\n"
                f"        auto* stage = new QWidget(host);\n"
                f"        stage->setFixedSize({w}, {h});\n"
            )
        setup = cpp["setup"].replace("%PARENT%", parent_expr)
        post_setup = spec.get("factorySetup", "").replace("%PARENT%", parent_expr)
        if post_setup and not post_setup.endswith("\n"):
            post_setup += "\n"
        factory_block = (
            f'    if (route == QStringLiteral("{route}")) {{\n{pre_setup}{setup}{post_setup}'
            f'        return {{{surface}, control}};\n    }}'
        )
        if guard:
            factory_block = f"#if defined({guard})\n{factory_block}\n#endif"
        factories.append(factory_block)
    route_lines = []
    for route, guard in routes.items():
        line = f'        QStringLiteral("{route}"),'
        if guard:
            route_lines.append(f"#if defined({guard})\n{line}\n#endif")
        else:
            route_lines.append(line)
    joined_routes = "\n".join(route_lines)
    source = "// Generated by tools/site/generate_playgrounds.py; edit components.json.\n"
    source += "\n".join(sorted(includes)) + "\n"
    for guard in sorted(guarded_includes):
        extra = sorted(guarded_includes[guard] - includes)
        if extra:
            source += f"#if defined({guard})\n" + "\n".join(extra) + "\n#endif\n"
    source += "\nnamespace fluent::gallery {\n"
    source += f"QStringList playgroundRoutes()\n{{\n    return {{\n{joined_routes}\n    }};\n}}\n\n"
    source += "PlaygroundControl createPlaygroundControl(const QString& route, QWidget* parent)\n{\n"
    source += "\n".join(factories) + "\n    return {};\n}\n} // namespace fluent::gallery\n"
    formatter = root / ".venv-format/bin/clang-format"
    if not formatter.is_file():
        formatter = root / ".venv-format/Scripts/clang-format.exe"
    if not formatter.is_file():
        formatter = Path(shutil.which("clang-format") or "clang-format")
    version = subprocess.run([str(formatter), "--version"], text=True, capture_output=True, check=True).stdout
    if "version 22.1.8" not in version:
        raise RuntimeError("Playground generation requires clang-format 22.1.8")
    source = subprocess.run([str(formatter)], input=source, text=True, capture_output=True, check=True).stdout
    result[root / "app/view/widgets/GalleryPlaygroundFactory.cpp"] = source
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--resource-dir", type=Path, help="Generate Qt resources in a build directory")
    args = parser.parse_args()
    if args.resource_dir is not None:
        write_resources(args.resource_dir)
        return
    stale = []
    for path, content in outputs(ROOT).items():
        data = content.encode("utf-8")
        if path.exists() and path.read_bytes() == data:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_bytes(data)
    if stale:
        raise SystemExit("Stale playground assets: " + ", ".join(stale))


if __name__ == "__main__":
    main()
